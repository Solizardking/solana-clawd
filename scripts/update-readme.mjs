#!/usr/bin/env node
/**
 * Auto-update README files with sections derived from CLAWD.md and CONSTITUTION.md.
 *
 * Usage:
 *   node scripts/update-readme.mjs              # update all targets
 *   node scripts/update-readme.mjs x402         # update x402/README.md only
 *
 * To wire into CI or a git hook, add to package.json scripts:
 *   "readme": "node scripts/update-readme.mjs"
 * and call `npm run readme` before committing.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const NOW = new Date().toISOString().slice(0, 10);

// ── Section extraction helpers ────────────────────────────────────────────────

function readFile(rel) {
  const p = join(ROOT, rel);
  if (!existsSync(p)) throw new Error(`Source not found: ${p}`);
  return readFileSync(p, "utf-8");
}

/** Extract a top-level ## section from a markdown document by heading text. */
function extractSection(md, heading) {
  const lines = md.split("\n");
  const startIdx = lines.findIndex((l) => l.trim() === `## ${heading}`);
  if (startIdx === -1) return null;
  const end = lines.findIndex((l, i) => i > startIdx && /^## /.test(l));
  return lines.slice(startIdx, end === -1 ? undefined : end).join("\n").trim();
}

/** Extract a bullet list item value from CLAWD.md-style documents. */
function extractBulletValue(md, label) {
  const match = md.match(new RegExp(`\\*\\*${label}\\*\\*[:\\s]+([^\n]+)`));
  return match ? match[1].trim() : null;
}

/** Extract the Three Laws block from CONSTITUTION.md or CLAWD.md. */
function extractThreeLaws(md) {
  const section = extractSection(md, "The Three Laws");
  if (!section) return null;
  const bullets = section
    .split("\n")
    .filter((l) => l.trim().startsWith("- **Law"))
    .join("\n");
  return bullets || null;
}

// ── Section injector ──────────────────────────────────────────────────────────

/**
 * Replace a delimited section in a README file.
 * Delimiters:
 *   <!-- AUTO-GENERATED SECTION START: <tag> -->
 *   <!-- AUTO-GENERATED SECTION END: <tag> -->
 */
function injectSection(readmePath, tag, newContent) {
  if (!existsSync(readmePath)) {
    console.warn(`  ⚠ README not found: ${readmePath}`);
    return false;
  }

  const src = readFileSync(readmePath, "utf-8");
  const startMarker = `<!-- AUTO-GENERATED SECTION START: ${tag} -->`;
  const endMarker = `<!-- AUTO-GENERATED SECTION END: ${tag} -->`;

  const startIdx = src.indexOf(startMarker);
  const endIdx = src.indexOf(endMarker);

  if (startIdx === -1 || endIdx === -1) {
    console.warn(`  ⚠ Markers for "${tag}" not found in ${readmePath} — skipping`);
    return false;
  }

  const header = `${startMarker}\n<!--\n  Generated by scripts/update-readme.mjs on ${NOW}\n  Source: CLAWD.md · CONSTITUTION.md\n  Run \`node scripts/update-readme.mjs\` to refresh.\n-->`;
  const updated =
    src.slice(0, startIdx) +
    header +
    "\n\n" +
    newContent.trim() +
    "\n\n" +
    src.slice(endIdx);

  writeFileSync(readmePath, updated, "utf-8");
  return true;
}

