// ── Targets ───────────────────────────────────────────────────────────────────

const TARGETS = {
  x402: {
    readme: "x402/README.md",
    sections: [
      { tag: "clawd-identity", builder: (clawd, constitution) => buildIdentitySection(clawd) },
      { tag: "clawd-constitution-excerpt", builder: buildConstitutionExcerpt },
    ],
  },
};

// ── Main ──────────────────────────────────────────────────────────────────────

const filter = process.argv[2];

let clawd, constitution;
try {
  clawd = readFile("CLAWD.md");
  constitution = readFile("CONSTITUTION.md");
} catch (e) {
  console.error(`✗ ${e.message}`);
  process.exit(1);
}

let updated = 0;
let skipped = 0;

for (const [name, target] of Object.entries(TARGETS)) {
  if (filter && name !== filter) continue;

  console.log(`\n▸ ${name} → ${target.readme}`);

  for (const { tag, builder } of target.sections) {
    const content = builder(clawd, constitution);
    const readmePath = join(ROOT, target.readme);
    const ok = injectSection(readmePath, tag, content);
    if (ok) {
      console.log(`  ✓ updated section: ${tag}`);
      updated++;
    } else {
      skipped++;
    }
  }
}

console.log(`\n  Done. ${updated} section(s) updated, ${skipped} skipped.\n`);
console.log(`  Run again after editing CLAWD.md or CONSTITUTION.md to keep READMEs in sync.`);
